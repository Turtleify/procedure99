interface Props {
  name: string
  size?: number
  stroke?: number
  className?: string
}

/** Line icon by name. Content files reference icons by these string keys. */
export function Icon({ name, size = 18, stroke = 1.6, className }: Props): JSX.Element {
  const C = ICONS[name] ?? Circle
  return <C size={size} strokeWidth={stroke} className={className} aria-hidden focusable={false} />
}

export const hasIcon = (name: string): boolean => name in ICONS
